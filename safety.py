_MAP=str.maketrans({'а':'a','е':'e','о':'o','р':'p','с':'c','х':'x','у':'y','т':'t','л':'l','г':'g','м':'m','б':'b','ф':'f','д':'d','и':'i','н':'n','0':'o','1':'l','3':'e','4':'a','5':'s','7':'t'})

def profile_text(kind, raw):
    text=unicodedata.normalize('NFKC',raw).strip()
    maximum=32 if kind=='name' else 45
    if kind not in ('name','bio') or not 1<=len(text)<=maximum:
        raise ValueError('Имя: 1-32 символа; описание: 1-45 символов.')
    if not re.fullmatch(r'[A-Za-zА-Яа-яЁё0-9 .,!?()\-]+',text):
        raise ValueError('Разрешены русские/латинские буквы, цифры и простая пунктуация, без ссылок и спецсимволов.')
    flat=re.sub('[^a-z0-9]','',text.casefold().translate(_MAP))
    blocked=('telegpam','botfaep','botfatep','botfap','telegram','telegr','botfather','botfazer','botfater','support','official','verified','admin','podder','poddep','ofic','offic','sluzhb','sluzb','durov','dupow')
    if any(x in flat for x in blocked):raise ValueError('Нельзя имитировать Telegram, BotFather, администрацию или официальную поддержку.')
    return ('Бульбанов AI | '+text) if kind=='name' else ('ИИ-участник чата. '+text)

def owner_command(is_private, outgoing, chat_id, sender_id, self_id, owner_id):
    return bool(is_private and ((outgoing and chat_id==self_id) or (not outgoing and sender_id==owner_id)))
